"""Writes carrier.kicad_sch from design.py (plain Python 3, no KiCad needed).

Label-style schematic: every pin gets a global net label, so the drawing stays
readable without wires. Symbol UUIDs match the footprint links written by
generate_pcb.py, so `kicad-cli pcb drc --schematic-parity` can compare both.
"""
import os
import uuid

import design

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "carrier.kicad_sch")


def uid(key):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "e-reader-carrier/" + key))


def sym_uuid(ref):
    return uid(ref)   # same scheme as generate_pcb.sym_uuid


ROOT = uid("root-sheet")


lib_symbol = design.lib_symbol


def q(s):
    return '"' + s.replace('\\\\', '\\\\\\\\').replace('"', '\\\\"') + '"'


FONT = "(effects (font (size 1.27 1.27)))"
HIDE = "(effects (font (size 1.27 1.27)) hide)"

# where each part goes on the A3 sheet (mm, KiCad schematic coordinates, y down)
LAYOUT = {
    "U1": (139.7, 129.54), "J1": (284.48, 101.6), "J3": (284.48, 200.66), "J2": (40.64, 63.5),
    "SW6": (78.74, 63.5),
    "SW1": (63.5, 223.52), "SW2": (93.98, 223.52), "SW3": (124.46, 223.52), "SW4": (154.94, 223.52),
    "SW5": (185.42, 223.52),
    "C1": (358.14, 76.2), "C2": (373.38, 76.2),
    "H1": (322.58, 254.0), "H2": (335.28, 254.0), "H3": (347.98, 254.0), "H4": (360.68, 254.0),
}
for i in range(5):
    LAYOUT[f"R{i + 1}"] = (236.22 + 12.7 * i, 63.5)
FLAGS = [("+3V3", (358.14, 50.8)), ("GND", (373.38, 50.8)), ("VBAT", (99.06, 50.8))]


def label(net, x, y, pin_angle):
    # the label points away from the symbol body
    angle = {0: 180, 180: 0, 90: 270, 270: 90}[pin_angle]
    just = "right" if angle in (180, 270) else "left"
    # global labels: net names without a sheet prefix, identical to the PCB's
    return (f'  (global_label {q(net)} (shape passive) (at {x:.2f} {y:.2f} {angle}) (fields_autoplaced yes) '
            f'(effects (font (size 1.27 1.27)) (justify {just})) (uuid {uid("lbl/" + net + f"/{x:.2f}/{y:.2f}")})\n'
            f'    (property "Intersheetrefs" "${{INTERSHEET_REFS}}" (at {x:.2f} {y:.2f} 0) {HIDE}))\n')


def symbol_instance(ref, lib_id, value, footprint, pos, pins, in_bom=True, mpn=""):
    x, y = pos
    out = [f'  (symbol (lib_id {q(lib_id)}) (at {x:.2f} {y:.2f} 0) (unit 1)\n',
           f'    (in_bom {"yes" if in_bom else "no"}) (on_board {"yes" if footprint else "no"}) (dnp no)\n',
           f'    (uuid {sym_uuid(ref)})\n',
           f'    (property "Reference" {q(ref)} (at {x:.2f} {y - 6:.2f} 0) {FONT})\n',
           f'    (property "Value" {q(value)} (at {x:.2f} {y + 6:.2f} 0) {FONT})\n',
           f'    (property "Footprint" {q(footprint)} (at {x:.2f} {y:.2f} 0) {HIDE})\n',
           f'    (property "Datasheet" "~" (at {x:.2f} {y:.2f} 0) {HIDE})\n']
    if mpn:
        out.append(f'    (property "MPN" {q(mpn)} (at {x:.2f} {y:.2f} 0) {HIDE})\n')
    for num in pins:
        out.append(f'    (pin {q(num)} (uuid {uid(ref + "/pin/" + num)}))\n')
    out.append(f'    (instances (project "carrier" (path "/{ROOT}" (reference {q(ref)}) (unit 1))))\n  )\n')
    return "".join(out)


def main():
    P = design.case_params()
    parts = design.parts(P)
    libs = {}
    body = []
    for p in parts:
        if p.symbol not in libs:
            libs[p.symbol] = lib_symbol(p.symbol)
        block, pins = libs[p.symbol]
        x, y = LAYOUT[p.ref]
        body.append(symbol_instance(p.ref, p.symbol, p.value, p.footprint, (x, y), pins,
                                    in_bom=not p.ref.startswith("H"), mpn=p.mpn))
        for num, (px, py, ang, _name) in pins.items():
            net = p.pins.get(num, "")
            ax, ay = x + px, y - py
            if net:
                body.append(label(net, ax, ay, ang))
            else:
                body.append(f'  (no_connect (at {ax:.2f} {ay:.2f}) (uuid {uid(p.ref + "/nc/" + num)}))\n')
    # power flags: these nets are fed from off-board (USB/battery through the Feather)
    libs["power:PWR_FLAG"] = lib_symbol("power:PWR_FLAG")
    _, fpins = libs["power:PWR_FLAG"]
    for i, (net, (x, y)) in enumerate(FLAGS):
        ref = f"#FLG0{i + 1}"
        body.append(symbol_instance(ref, "power:PWR_FLAG", "PWR_FLAG", "", (x, y), fpins, in_bom=False))
        px, py, ang, _ = fpins["1"]
        body.append(label(net, x + px, y - py, ang))

    # notes
    gpio = ", ".join(f"{pad}=IO{g}" for pad, g in sorted(design.FEATHER_GPIO.items()))
    notes = [
        "Carrier board: FeatherS3 + Waveshare 4.2in e-paper V2 + microSD + 5 buttons.",
        "Generated by generate_sch.py from design.py; edit design.py, not this file.",
        "Feather pad -> FeatherS3 GPIO: " + gpio,
        "J3 to the display cable: VCC GND DIN CLK CS DC RST BUSY PWR (Waveshare Rev2.2 order).",
        "SW6 is in the battery line: the battery only charges while the switch is ON.",
    ]
    for i, t in enumerate(notes):
        body.append(f'  (text {q(t)} (exclude_from_sim no) (at 20.32 {266.7 + 5.08 * i:.2f} 0) '
                    f'(effects (font (size 1.524 1.524)) (justify left)) (uuid {uid("note" + str(i))}))\n')

    sch = ["(kicad_sch (version 20231120) (generator \"e-reader-gen\") (generator_version \"1.0\")\n",
           f"  (uuid {ROOT})\n  (paper \"A3\")\n",
           "  (title_block (title \"e-reader carrier board\") (rev \"1\") (comment 1 \"github.com/ljunker/e-reader\"))\n",
           "  (lib_symbols\n"]
    for block, _ in libs.values():
        sch.append("    " + block.replace("\n", "\n    ") + "\n")
    sch.append("  )\n")
    sch.extend(body)
    sch.append('  (sheet_instances (path "/" (page "1")))\n)\n')
    open(OUT, "w").write("".join(sch))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
